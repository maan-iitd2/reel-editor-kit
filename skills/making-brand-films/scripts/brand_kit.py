_probe_cache = {}


def probe(url, limit=200_000):
    """(http status, first `limit` bytes); 0 on network failure. Never raises."""
    if (url, limit) in _probe_cache: return _probe_cache[(url, limit)]
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
            out = (r.status, r.read(limit))
    except urllib.error.HTTPError as e: out = (e.code, b"")
    except Exception: out = (0, b"")
    _probe_cache[(url, limit)] = out
    return out


def fetch_bytes(url):
    status, body = probe(url, 20_000_000)
    if status != 200: raise RuntimeError(f"HTTP {status} for {url[:90]}")
    return body


# ---------- colour maths ----------
def rgb(h): h = h.lstrip("#"); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def hexc(c): return "#%02x%02x%02x" % tuple(max(0, min(255, int(round(v)))) for v in c)
def dist(a, b): return math.dist(rgb(a), rgb(b))
def mix(a, b, t): return hexc([x * (1 - t) + y * t for x, y in zip(rgb(a), rgb(b))])
def hls(h): r, g, b = (v / 255 for v in rgb(h)); hh, l, s = colorsys.rgb_to_hls(r, g, b); return hh * 360, l, s
def from_hls(h, l, s): return hexc([v * 255 for v in colorsys.hls_to_rgb(h / 360 % 1, l, s)])
def hue_gap(a, b): d = abs(hls(a)[0] - hls(b)[0]) % 360; return min(d, 360 - d)


def lum(h):
    f = lambda v: v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (f(v / 255) for v in rgb(h)); return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b): x, y = sorted((lum(a), lum(b)), reverse=True); return (x + 0.05) / (y + 0.05)


def norm_hex(s):
    s = s.lstrip("#").lower()
    if len(s) == 3: s = "".join(c * 2 for c in s)
    return "#" + s[:6]


def kmeans(img, k=5):
    """Dominant colours of an image as [(hex, share)], transparent pixels ignored. Deterministic."""
    im = img.convert("RGBA"); im.thumbnail((120, 120))
    a = np.asarray(im).reshape(-1, 4); px = a[a[:, 3] > 128][:, :3].astype(float)
    if len(px) == 0: return []
    rng = np.random.default_rng(0); cen = [px[rng.integers(len(px))]]
    for _ in range(k - 1):  # k-means++ seeding
        d = np.min([((px - c) ** 2).sum(1) for c in cen], axis=0)
        cen.append(px[rng.choice(len(px), p=d / d.sum())] if d.sum() > 0 else px[0])
    cen = np.array(cen)
    for _ in range(12):
        lab = ((px[:, None, :] - cen[None]) ** 2).sum(2).argmin(1)
        for i in range(len(cen)):
            if (lab == i).any(): cen[i] = px[lab == i].mean(0)
    share = np.bincount(lab, minlength=len(cen)) / len(px)
    return sorted(((hexc(c), float(s)) for c, s in zip(cen, share) if s >= 0.03), key=lambda t: -t[1])


# ---------- site scrape ----------
def norm_site(arg):
    if not re.match(r"https?://", arg): arg = "https://" + arg
    u = urllib.parse.urlparse(arg)
    return f"{u.scheme}://{u.netloc}", u.netloc


def slug_of(host):
    p = host.lower().split(":")[0].removeprefix("www.").split(".")
    s = p[-3] if len(p) >= 3 and p[-2] in ("co", "com", "org", "net", "ac", "gov") else (p[-2] if len(p) >= 2 else p[0])
    return re.sub(r"[^a-z0-9-]", "", s)


def collect_css(html, base):
    css = "".join(re.findall(r"<style[^>]*>(.*?)</style>", html, re.S))
    n = 0
    for tag in re.findall(r"<link\b[^>]*>", html):
        if "stylesheet" not in tag or n >= 10: continue
        m = re.search(r'href=["\']([^"\']+)', tag)
        if not m: continue
        n += 1
        try: css += "\n" + get(urllib.parse.urljoin(base + "/", htmllib.unescape(m.group(1))))
        except Exception as e: print("  (skip css", m.group(1)[:70], e, ")")
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def attrs(tag): return {k.lower(): htmllib.unescape(v) for k, v in re.findall(r'([\w:-]+)\s*=\s*["\']([^"\']*)["\']', tag)}


def meta(html, key):
    for tag in re.findall(r"<meta\b[^>]*>", html):
        a = attrs(tag)
        if a.get("property") == key or a.get("name") == key: return a.get("content", "")
    return ""


def links_google_families(html):
    out = []
    for u in re.findall(r'href=["\']([^"\']*fonts\.googleapis\.com/css[^"\']*)', html):
        for f in urllib.parse.parse_qs(urllib.parse.urlparse(htmllib.unescape(u)).query).get("family", []):
            out.append(f.split(":")[0].replace("+", " "))
    return out


# ---------- fonts ----------
def parse_stack(v):
    v = re.sub(r"!important", "", v)
    return [x.strip().strip("'\"").strip() for x in re.findall(r"""("[^"]+"|'[^']+'|[^,]+)""", v) if x.strip()]


def resolve_vars(v, vars_):
    for _ in range(4): v = re.sub(r"var\(\s*(--[\w-]+)\s*(?:,[^)]*)?\)", lambda m: vars_.get(m.group(1), ""), v)
    return v


def sel_role(sel):
    s = sel.lower()
    if re.search(r"\bh[1-4]\b|heading|title|display|headline|hero", s): return "headline"
    if re.search(r"button|\.btn|label|\bnav|menu|kicker|eyebrow|caption|badge|\binput|select|footer|small", s): return "ui"
    if re.search(r"(^|[\s,])(html|body|:root|\*)([\s,.:\[{]|$)|\bp\b|\.text|\.rte|prose|paragraph", s): return "body"
    return "other"


def var_role(name):
    n = name.lower()
    if re.search(r"head|title|display", n): return "headline"
    if re.search(r"body|text|base|paragraph|main", n): return "body"
    if re.search(r"button|nav|ui|label|accent|secondary|alt", n): return "ui"
    return "other"


def font_faces(css):
    faces = {}
    for blk in re.findall(r"@font-face\s*\{([^}]*)\}", css):
        f = re.search(r"font-family:\s*['\"]?([^;'\"]+)", blk)
        if f: faces.setdefault(f.group(1).strip().lower(), []).extend(re.findall(r"url\(['\"]?([^)'\"]+)", blk))
    return faces


def family_label(name, urls):
    """Next.js/next-font build names a family after a JS identifier ("fontAbcSocial"): the real name lives in the file name (ABCSocial_Regular.woff2)."""
    if not re.fullmatch(r"font[A-Z]\w*", name): return name
    stem = next((m.group(1) for m in (re.match(r"([A-Za-z]{3,})", os.path.basename(u.split("?")[0])) for u in urls) if m), re.sub(r"^font", "", name))
    return re.sub(r"(?<=[a-z])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", stem)


def face_origin(urls, site_host):
    u = " ".join(urls).lower()
    if not u: return None
    if "typekit" in u or "fonts.adobe" in u: return "Adobe Fonts (@font-face)"
    if "gstatic.com" in u: return "Google Fonts (@font-face)"
    if "fontshare" in u: return "Fontshare (@font-face)"
    host = urllib.parse.urlparse(next((x for x in urls if x.startswith(("http", "//"))), "")).netloc or site_host
    return f"self-hosted @font-face ({host})"


def parse_css(css):
    """-> (custom properties {--x: value}, [(selector, declarations)]) with @font-face blocks removed."""
    body = re.sub(r"@font-face\s*\{[^}]*\}", "", css)
    return {n: v.strip() for n, v in re.findall(r"(--[\w-]+)\s*:\s*([^;{}]+)", body)}, re.findall(r"([^{}@][^{}]*)\{([^{}]*)\}", body)


def find_fonts(css, html, site_host):
    """-> (ordered role dict {headline, body, ui: {name, generic, origin}}, other fonts, votes)"""
    faces = font_faces(css)
    vars_, rules = parse_css(css)
    votes = collections.defaultdict(collections.Counter); generic = {}

    def vote(stack, role, w):
        names = parse_stack(resolve_vars(stack, vars_))
        gen = next((x.lower() for x in names if x.lower() in GENERIC), "")
        for nm in names:
            low = nm.lower()
            if low in GENERIC or low.startswith(("var(", "-")) or ICON.search(nm) or "fallback" in low: continue
            if low in SYSTEM and low not in faces: continue
            if re.search(r"\b(arabic|hebrew|cjk|thai|devanagari|japanese|korean|hindi|sc|tc|jp|kr)\b", low): continue
            votes[nm][role] += w; votes[nm]["total"] += w; generic.setdefault(nm, gen)
            break  # the first real name in a stack is the design intent; the rest are fallbacks

    for n, v in vars_.items():
        if "font" in n and "family" in n or re.search(r"--(font|type)[\w-]*(head|body|title|display|text|base)", n): vote(v, var_role(n), 3)
    for sel, body in rules:
        m = re.search(r"font-family:\s*([^;]+)", body)
        if not m: continue
        for part in sel.split(","): vote(m.group(1), sel_role(part), 1)
    for fam in links_google_families(html):
        votes[fam]["total"] += 1; votes[fam]["other"] += 1; generic.setdefault(fam, "")
    ranked = [n for n, _ in sorted(votes.items(), key=lambda kv: -kv[1]["total"])]
    info = lambda n: {"name": family_label(n, faces.get(n.lower(), [])), "css_name": n, "generic": generic.get(n, ""), "origin": face_origin(faces.get(n.lower(), []), site_host)
                      or ("Google Fonts <link>" if n in links_google_families(html) else "css font-family only")}
    if not ranked: return {}, [], votes
    top = lambda role, skip=(): next((n for n in sorted(ranked, key=lambda n: -votes[n][role]) if votes[n][role] > 0 and n not in skip), None)
    head = top("headline") or ranked[0]
    body = top("body") or next((n for n in ranked if n != head), head)
    ui = top("ui", skip=(head,)) or body
    roles = {"headline": info(head), "body": info(body), "ui": info(ui)}
    used = {head, body, ui}
    return roles, [i for i in map(info, ranked) if i["css_name"] not in used and not i["origin"].startswith("css font-family")][:3], votes


def google_url(name, role):
    q = name.replace(" ", "+")
    ladder = (["ital,wght@0,400;0,700;1,400;1,700", "ital,wght@0,400;1,400", "wght@400;700"] if role == "headline"
              else ["wght@400;500;700", "wght@400;700", "wght@400"])
    if probe(f"https://fonts.googleapis.com/css2?family={q}&display=swap", 1)[0] != 200: return None  # unknown family answers 400
    for spec in ladder:
        u = f"https://fonts.googleapis.com/css2?family={q}:{spec}&display=swap"
        if probe(u, 1)[0] == 200: return u
    return f"https://fonts.googleapis.com/css2?family={q}&display=swap"


def fontshare_url(name, role):
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    for w in ["400,500,700", "400,700", "400", None]:  # Fontshare answers 200 for anything: only an @font-face body proves it
        u = f"https://api.fontshare.com/v2/css?f[]={slug}" + (f"@{w}" if w else "") + "&display=swap"
        if b"@font-face" in probe(u)[1]: return u
    return None


def name_variants(name):
    """Framework builds mangle family names ("fontAbcSocial", "NotionInter"): try the name, a spaced form, then its trailing words."""
    spaced = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", re.sub(r"^font(?=[A-Z])", "", name)).strip()
    words = spaced.split(); out = [name, spaced] + [" ".join(words[-n:]) for n in (2, 1) if len(words) > n]
    return [v for i, v in enumerate(out) if v not in out[:i] and len(v) >= 4 and v.lower() not in ("sans", "serif", "display", "text", "mono", "regular", "light", "bold")]


def locate_any(name, role, prefer=None):
    for v in name_variants(name):
        u = locate_free(v, role, prefer)
        if u: return dict(u, matched_as=v) if v != name else u
    return None


def locate_free(name, role, prefer=None):
    """Find `name` on Google Fonts or Fontshare and prove it loads (CSS 200 + first font file 200). None if it is on neither."""
    order = [prefer] if prefer else []
    order += [s for s in ("google", "fontshare") if s not in order]
    for src in order:
        url = (google_url if src == "google" else fontshare_url)(name, role)
        if not url: continue
        st, css = probe(url)
        m = re.search(r"url\(['\"]?([^)'\"]+)", css.decode("utf8", "ignore"))
        furl = ("https:" + m.group(1)) if m and m.group(1).startswith("//") else (m.group(1) if m else "")
        fst = probe(furl, 1)[0] if furl else 0
        slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
        where = (f"https://fonts.google.com/specimen/{name.replace(' ', '+')}" if src == "google" else f"https://www.fontshare.com/fonts/{slug}")
        return {"name": name, "source": src, "css_url": url, "where": where, "css_status": st, "file_status": fst, "loads": st == 200 and fst == 200}
    return None


def category_of(name, generic):
    if generic == "monospace" or re.search(r"mono|code", name, re.I): return "mono"
    if generic == "cursive" or re.search(r"script|hand", name, re.I): return "script"
    if generic == "serif" or re.search(r"serif(?! *sans)|journal|garamond|didot|caslon|bodoni|baskerville|roman|antiqua|text$", name, re.I): return "serif"
    return "sans"


def standin(name, generic, role, feeling):
    flat = lambda t: re.sub(r"[^a-z]", "", t.lower())
    cands = [v for k, v in DATA["paid_standins"].items() if len(flat(name)) >= 6 and (flat(k).startswith(flat(name)) or flat(name).startswith(flat(k)))]
    cat = category_of(name, generic); F = DATA["fonts"]
    paired = [p[role] for p in DATA["pairings"][feeling]]
    pool = [n for n, m in F.items() if m["category"] == cat or (cat == "sans" and m["category"] == "rounded")]
    pool.sort(key=lambda n: (n not in paired, feeling not in F[n]["feelings"]))
    for n in cands + pool + list(F):
        yield n


def resolve_fonts(css, html, site_host, feeling):
    roles, others, _ = find_fonts(css, html, site_host)
    out = []
    for role, f in list(roles.items()) + [("other", o) for o in others]:
        name = f["name"]; free = locate_any(name, role if role != "other" else "body")
        rec = {"role": role, "brand_font": name, "brand_source": f["origin"], "license": "free" if free else "paid-or-custom (check the foundry)"}
        if f["css_name"] != name: rec["css_family"] = f["css_name"]
        if free: rec["use"] = dict(free, standin=False)
        else:
            for cand in standin(name, f["generic"], role if role != "other" else "body", feeling):
                u = locate_free(cand, role if role != "other" else "body", DATA["fonts"].get(cand, {}).get("source"))
                if u and u["loads"]: rec["use"] = dict(u, standin=True); break
        out.append(rec)
    return out


# ---------- colours ----------
HINTS = {"accent": r"accent|primary|brand|highlight|^--colou?r-"}  # --color-<name> is the usual design-token spelling; neutrals drop out on saturation
NOISE_VAR = re.compile(r"shadow|overlay|error|success|warn|danger|rating|star|focus|gradient|border|outline|disabled|placeholder|input|badge|announcement|header|footer|card")
# UI-library defaults ("--swiper-theme-color:#007aff" is Swiper's blue, not the brand's) never count as brand evidence
LIB_VAR = re.compile(r"--(swiper|bs|tw|wp|shopify|mdc|mat|mui|ant|chakra|mantine|splide|glide|flickity|fancybox|pswp|plyr|vjs|leaflet|toastify|radix|tippy|rdp|fa|yt|jdgm|spr|klaviyo|kl)-", re.I)


def css_colors(css):
    """-> (weights {hex: [score, sources]}, hints {role: Counter(hex)})"""
    w = collections.defaultdict(lambda: [0.0, set()]); hints = collections.defaultdict(collections.Counter); cnt = collections.Counter()
    for prop, val in re.findall(r"([\w-]+)\s*:\s*([^;{}]+)", css):
        p = prop.lower()
        if not (p.startswith("--") or re.search(r"color|background|border|fill|stroke", p)) or LIB_VAR.match(p) or LIB_VAR.search(val): continue
        found = [norm_hex(m) for m in re.findall(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b", val) if len(m) != 4 or re.search(r"color|background|border|fill|stroke|^--", p)]
        found += [hexc(tuple(map(int, t))) for t in re.findall(r"rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)", val)]
        t = re.fullmatch(r"\s*(\d{1,3})[\s,]+(\d{1,3})[\s,]+(\d{1,3})\s*", val)
        if t and p.startswith("--") and max(map(int, t.groups())) <= 255: found.append(hexc(tuple(map(int, t.groups()))))
        for h in found:
            cnt[h] += 1
            if p.startswith("--") and not NOISE_VAR.search(p):
                for role, pat in HINTS.items():
                    if re.search(pat, p): hints[role][h] += 1
    for h, n in cnt.items(): w[h][0] += 3 * math.log2(1 + n); w[h][1].add("css")
    return w, hints


def body_colors(css):
    """Page background and text colour from html/body/:root rules -> {'background': hex, 'ink': hex} (what the visitor really sees)."""
    vars_, rules = parse_css(css); out = {}
    for sel, body in rules:
        if not re.fullmatch(r"\s*(html|body|:root|html\s*,\s*body)\s*", sel): continue
        for key, pat in (("background", r"(?<![\w-])background(?:-color)?:\s*([^;]+)"), ("ink", r"(?<![\w-])color:\s*([^;]+)")):
            m = re.search(pat, body)
            if not m: continue
            val = resolve_vars(m.group(1), vars_)
            c = re.search(r"#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b", val); r = re.search(r"rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)", val)
            if c: out.setdefault(key, norm_hex(c.group(0)))
            elif r: out.setdefault(key, hexc(tuple(map(int, r.groups()))))
            elif re.match(r"\s*(white|#fff)\b", val): out.setdefault(key, "#ffffff")
            elif re.match(r"\s*(black)\b", val): out.setdefault(key, "#000000")
    return out


def merge_colors(w, tol=26):
    reps = []
    for h, (s, src) in sorted(w.items(), key=lambda kv: -kv[1][0]):
        for r in reps:
            if dist(r[0], h) < tol: r[1] += s; r[2] |= src; break
        else: reps.append([h, s, set(src)])
    return sorted(reps, key=lambda r: -r[1])


def build_palette(weights, hints, archetype):
    """weights: {hex: [score, sources]}. Returns {role: (hex, source)} with all 7 roles; gaps are derived, never left empty."""
    reps = merge_colors(weights)
    for role, cnts in hints.items():  # a named theme variable is stronger evidence than raw frequency
        for h, n in cnts.items():
            if hls(h)[2] < .25: continue
            for r in reps:
                if dist(r[0], h) < 26: r[1] += 8 + n; r[2].add("css"); break
    reps.sort(key=lambda r: -r[1])
    HLS = {r[0]: hls(r[0]) for r in reps}
    pal = {}; srcs = {r[0]: "+".join(sorted(r[2])) for r in reps}
    sat = [r[0] for r in reps if HLS[r[0]][2] >= .25 and .1 <= HLS[r[0]][1] <= .85]  # .1: dark navy tokens are brand colours too
    bg_h = next((h for h, n in hints.get("background", collections.Counter()).most_common() if HLS.get(h, hls(h))[1] > .9 or hls(h)[1] < .15), None)
    light = [r[0] for r in reps if HLS[r[0]][1] >= .9 and HLS[r[0]][2] < .4]
    bg = bg_h or (light[0] if light else "#ffffff")
    pal["background"] = (bg, "css" if (bg_h or light) else "derived")
    if sat: acc = sat[0]; pal["accent"] = (acc, srcs[acc])
    else: acc = None
    def ink_ok(h, need): return contrast(h, bg) >= need
    ink = next((h for h, _ in hints.get("ink", collections.Counter()).most_common() if ink_ok(h, 4.5)), None)
    ink = ink or next((r[0] for r in reps if ink_ok(r[0], 7) and HLS[r[0]][2] < .5 and r[0] != acc), None)
    if ink: pal["ink"] = (ink, "css")
    else:
        dark = lum(bg) < .2; ink = "#f4f4f0" if dark else mix(acc or "#000000", "#000000", .85) if acc else "#111111"
        pal["ink"] = (ink, "derived")
    if acc is None:  # monochrome brand: ink is the brand colour, accent2 borrows the archetype
        acc = pal["ink"][0]; pal["accent"] = (acc, "derived:monochrome")
    a_h = hls(acc)
    a2 = next((h for h in sat[1:] if hue_gap(h, acc) >= 30 and dist(h, acc) >= 70), None)
    pal["accent2"] = (a2, srcs[a2]) if a2 else (from_hls(a_h[0] + 40, min(.6, max(.4, a_h[1])), max(.45, a_h[2])), "derived") if sat else (archetype["accent2"], f"archetype:{archetype['name']}")
    near = lambda h: HLS.get(h, hls(h))[2] >= .1 and hue_gap(h, acc) <= 45 and dist(h, acc) >= 25
    soft = next((r[0] for r in reps if HLS[r[0]][1] >= .82 and near(r[0]) and r[0] != bg), None)
    pal["soft"] = (soft, srcs[soft]) if soft else (mix(acc, "#ffffff", .85) if lum(bg) > .2 else mix(acc, bg, .8), "derived")
    deep = next((r[0] for r in reps if HLS[r[0]][1] <= .32 and near(r[0]) and HLS[r[0]][2] >= .2), None)
    pal["deep"] = (deep, srcs[deep]) if deep else (mix(acc, "#000000", .5), "derived")
    muted = next((r[0] for r in reps if .35 < HLS[r[0]][1] < .75 and HLS[r[0]][2] < .2), None)
    pal["muted"] = (muted, srcs[muted]) if muted else (mix(pal["ink"][0], bg, .55), "derived")
    return {r: pal[r] for r in ROLES}, reps


