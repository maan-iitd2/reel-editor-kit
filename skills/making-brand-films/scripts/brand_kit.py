def strip_tags(s): return re.sub(r"\s+", " ", htmllib.unescape(re.sub(r"<[^>]+>", " ", s))).strip()


def page_text(html):
    heads = []
    for h in re.findall(r"<h[1-3]\b[^>]*>(.*?)</h[1-3]>", html, re.S):
        t = strip_tags(h)
        if 2 <= len(t) <= 120 and t not in heads and not re.search(r"cookie|menu|cart|search|close|skip|subscribe|navigation", t, re.I): heads.append(t)
    return {"title": strip_tags(re.search(r"<title[^>]*>(.*?)</title>", html, re.S).group(1)) if "<title" in html else "",
            "description": meta(html, "og:description") or meta(html, "description"), "site_name": strip_tags(meta(html, "og:site_name")), "headings": heads[:30]}


def feeling_scores(corpus, pal=None, lower_share=0.0, catalog=""):
    """Keyword votes: site copy counts 2 per hit (max 3 hits per keyword); the product catalogue only 1 per keyword, since product and colour
    names ("Tree Runner", "Natural White", "Limited Allbirds" x134) repeat and say little about the brand's voice. Short stems match whole words."""
    def count(k, t): return min(3, len(re.findall(r"\b" + re.escape(k) + (r"\b" if len(k) <= 4 else ""), t)))
    text, cat = corpus.lower(), catalog.lower(); hit = lambda k: 2 * count(k, text) + bool(count(k, cat))
    sc = {f: sum(hit(k) for k in m["keywords"]) for f, m in DATA["feelings"].items()}
    hits = {f: [k for k in m["keywords"] if hit(k)] for f, m in DATA["feelings"].items()}
    if pal:
        _, l, s = hls(pal["accent"][0]); dark = lum(pal["background"][0]) < .2
        if dark: sc["hype"] += 2
        elif s > .6 and l > .45: sc["playful"] += 1
        elif s < .5: sc["calm"] += 1
    sc["playful"] += 0.5 * lower_share
    pick = max(DATA["feelings"], key=lambda f: (sc[f], -list(DATA["feelings"]).index(f)))
    return pick, sc, hits[pick][:6]


def voice(txt, products):
    lines = txt["headings"] or [p["title"] for p in products[:12]]
    allt = " ".join(lines + [txt["description"]]).lower(); n = max(1, len(lines))
    lower = sum(1 for t in lines if t == t.lower() and re.search("[a-z]", t)) / n
    caps = sum(1 for t in lines if t.isupper()) / n
    words = statistics.median([len(t.split()) for t in lines]) if lines else 0
    notes = []
    if lines:
        notes.append("Headlines are lowercase" if lower >= .7 else "Headlines are UPPERCASE" if caps >= .6 else "Headlines use normal sentence/title case")
        notes[-1] += f" ({round(max(lower, caps) * 100) if max(lower, caps) >= .6 else round((1 - lower - caps) * 100)}% of {len(lines)} sampled)."
        notes.append(f"Short copy: median {words:g} words per heading." if words <= 6 else f"Longer copy: median {words:g} words per heading.")
    you, we = len(re.findall(r"\byou(r|'re)?\b", allt)), len(re.findall(r"\b(we|our|us)\b", allt))
    if you or we: notes.append("Talks to the reader (you/your)." if you >= we else "Speaks as 'we'.")
    if "?" in allt: notes.append("Asks questions in headlines/copy.")
    if allt.count("!") >= 2: notes.append("Uses exclamations.")
    if re.search("[\U0001F300-\U0001FAFF☀-➿]", allt): notes.append("Emoji appear in site copy.")
    samples = [t for t in sorted(lines, key=len) if 8 <= len(t) <= 60][:4]
    return {"notes": notes, "positioning": (txt["description"] if len(txt["description"]) <= 200 else txt["description"][:200].rsplit(" ", 1)[0] + "..."), "sample_headlines": samples,
            "metrics": {"lowercase_share": round(lower, 2), "uppercase_share": round(caps, 2), "median_words": words, "headings_sampled": len(lines)}}, lower


