def find_logo(html, base, host):
    """Candidate logos best-first: [(score, kind, ref, why)] where kind is url|svg."""
    c = []
    home = rf'href=["\'](?:/|{re.escape(base)}/?|https?://{re.escape(host)}/?)["\']'
    for m in re.finditer(rf"<a\b[^>]*{home}[^>]*>(.*?)</a>", html, re.S):
        inner = m.group(1)
        im = re.search(r"<img\b[^>]*>", inner)
        if im:
            a = attrs(im.group(0)); src = a.get("src") or a.get("data-src", "")
            if src and not src.startswith("data:"): c.append((60 + 5 * ("logo" in im.group(0).lower()), "url", src, "img in home link"))
        sv = re.search(r"<svg\b.*?</svg>", inner, re.S)
        if sv and re.search(r"<(path|polygon|rect|circle|text)\b", sv.group(0)): c.append((58, "svg", sv.group(0), "inline svg in home link"))
    for tag in re.findall(r"<img\b[^>]*>", html):
        a = attrs(tag); src = a.get("src") or a.get("data-src", "")
        blob = " ".join([src, a.get("class", ""), a.get("alt", ""), a.get("id", "")]).lower()
        if src and not src.startswith("data:") and "logo" in blob and not re.search(r"press|partner|payment|trust|footer|review|badge|client", blob):
            c.append((40, "url", src, "img with 'logo' in its name"))
    for blob in re.findall(r'<script[^>]*ld\+json[^>]*>(.*?)</script>', html, re.S):
        for u in re.findall(r'"logo"\s*:\s*(?:\{[^}]*?"(?:url|contentUrl)"\s*:\s*)?"([^"]+)"', blob):
            c.append((50, "url", u.replace("\\/", "/"), "JSON-LD Organization.logo"))
    for tag in re.findall(r"<link\b[^>]*>", html):
        a = attrs(tag)
        if "icon" in a.get("rel", "") and a.get("href"): c.append((25 if "apple" in a["rel"] else 20, "url", a["href"], a["rel"]))
    return sorted(c, key=lambda t: -t[0])


def parse_brandfetch(d):
    """Brandfetch v2 brand JSON -> {colors, fonts, logos}. Field names follow the public docs; untested with a live key."""
    logos = [f["src"] for lg in d.get("logos", []) if lg.get("type") == "logo" for f in lg.get("formats", []) if f.get("src")]
    logos.sort(key=lambda u: (not u.endswith(".svg"), not u.endswith(".png")))
    return {"colors": [norm_hex(c["hex"]) for c in d.get("colors", []) if c.get("hex")], "fonts": [f["name"] for f in d.get("fonts", []) if f.get("name")], "logos": logos}


def brandfetch(domain):
    key = os.environ.get("BRANDFETCH_API_KEY")
    if not key: return None
    try:
        req = urllib.request.Request(f"https://api.brandfetch.io/v2/brands/{domain}", headers={"Authorization": "Bearer " + key, "User-Agent": UA["User-Agent"]})
        return parse_brandfetch(json.loads(urllib.request.urlopen(req, timeout=30).read()))
    except Exception as e: print("  (brandfetch failed:", type(e).__name__, ")"); return None


def svg_size(svg):
    vb = re.search(r"viewBox=[\"']\s*[-\d.]+[\s,]+[-\d.]+[\s,]+([\d.]+)[\s,]+([\d.]+)", svg)
    return {"width": round(float(vb.group(1))), "height": round(float(vb.group(2)))} if vb else {"width": None, "height": None}


